// bdc 0x088632b8 BtlAttackIdUsesHitCounter
#include "bdc.h"

/* Returns 1 for the attack ids 0x31, 0x33, 0x34, 0x3e, 0x3f, 0x44, 0x47, 0x48, 0x4d, 0x5b, 0x5c,
   0x85..0x87, 0x91, 0x93, 0x94, 0x97, 0x98, 0x9c, 0x9f, 0xa0 and 0xba, else 0. `bakugan` is
   unused. The compiled code dispatches 0x31..0x4d and 0x85..0xa0 through jump tables. */
int BtlAttackIdUsesHitCounter(void *bakugan, int attackId)
{
    (void)bakugan;
    switch (attackId) {
    case 0x31:
    case 0x33:
    case 0x34:
    case 0x3e:
    case 0x3f:
    case 0x44:
    case 0x47:
    case 0x48:
    case 0x4d:
    case 0x5b:
    case 0x5c:
    case 0x85:
    case 0x86:
    case 0x87:
    case 0x91:
    case 0x93:
    case 0x94:
    case 0x97:
    case 0x98:
    case 0x9c:
    case 0x9f:
    case 0xa0:
    case 0xba:
        return 1;
    default:
        return 0;
    }
}
