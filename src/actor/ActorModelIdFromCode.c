#include "bdc.h"

/* Maps the character code stored in a placement record (byte `+0x36`) to the `ActorSpawn` model
   id (index into the GMO name table `0x08ab0308`): codes 0..0xc -> 0x23..0x2f (the named characters
   `00_Dan` ... `12_Edit_man`, except 7 -> 0x54 and 10 -> 0x55, the quest boats), 0xf..0x32 -> the
   NPC models 0x30..0x53 (in a shuffled order), 0x33..0x52 -> the Bakugan models 1..0x20. Unknown
   codes (0xd, 0xe, >= 0x53) give 0x23. */

u8 ActorModelIdFromCode(u8 code)
{
  u8 id = 0x23;

  switch (code) {
  case 0x00: return 0x23;
  case 0x01: return 0x24;
  case 0x02: return 0x25;
  case 0x03: return 0x26;
  case 0x04: return 0x27;
  case 0x05: return 0x28;
  case 0x06: return 0x29;
  case 0x07: return 0x54;
  case 0x08: return 0x2b;
  case 0x09: return 0x2c;
  case 0x0a: return 0x55;
  case 0x0b: return 0x2e;
  case 0x0c: return 0x2f;
  case 0x0f: return 0x30;
  case 0x10: return 0x31;
  case 0x11: return 0x32;
  case 0x12: return 0x33;
  case 0x13: return 0x34;
  case 0x14: return 0x35;
  case 0x15: return 0x3c;
  case 0x16: return 0x3d;
  case 0x17: return 0x3e;
  case 0x18: return 0x3f;
  case 0x19: return 0x40;
  case 0x1a: return 0x41;
  case 0x1b: return 0x48;
  case 0x1c: return 0x49;
  case 0x1d: return 0x4a;
  case 0x1e: return 0x4b;
  case 0x1f: return 0x4c;
  case 0x20: return 0x4d;
  case 0x21: return 0x42;
  case 0x22: return 0x43;
  case 0x23: return 0x44;
  case 0x24: return 0x45;
  case 0x25: return 0x46;
  case 0x26: return 0x47;
  case 0x27: return 0x36;
  case 0x28: return 0x37;
  case 0x29: return 0x38;
  case 0x2a: return 0x39;
  case 0x2b: return 0x3a;
  case 0x2c: return 0x3b;
  case 0x2d: return 0x4e;
  case 0x2e: return 0x4f;
  case 0x2f: return 0x50;
  case 0x30: return 0x51;
  case 0x31: return 0x52;
  case 0x32: return 0x53;
  case 0x33: return 0x01;
  case 0x34: return 0x02;
  case 0x35: return 0x03;
  case 0x36: return 0x04;
  case 0x37: return 0x05;
  case 0x38: return 0x06;
  case 0x39: return 0x07;
  case 0x3a: return 0x08;
  case 0x3b: return 0x09;
  case 0x3c: return 0x0a;
  case 0x3d: return 0x0b;
  case 0x3e: return 0x0c;
  case 0x3f: return 0x0d;
  case 0x40: return 0x0e;
  case 0x41: return 0x0f;
  case 0x42: return 0x10;
  case 0x43: return 0x11;
  case 0x44: return 0x12;
  case 0x45: return 0x13;
  case 0x46: return 0x14;
  case 0x47: return 0x15;
  case 0x48: return 0x16;
  case 0x49: return 0x17;
  case 0x4a: return 0x18;
  case 0x4b: return 0x19;
  case 0x4c: return 0x1a;
  case 0x4d: return 0x1b;
  case 0x4e: return 0x1c;
  case 0x4f: return 0x1d;
  case 0x50: return 0x1e;
  case 0x51: return 0x1f;
  case 0x52:
    id = 0x20;
    break;
  }
  return id;
}
